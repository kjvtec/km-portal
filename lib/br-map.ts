export function getPageForBr(code: string): number {
  if (brPageMap[code]) return brPageMap[code];

  // Try parent hierarchy: e.g. BR-01-01-04 -> BR-01-01
  const parts = code.split("-");
  if (parts.length === 4) {
    const parent = parts.slice(0, 3).join("-");
    if (brPageMap[parent]) return brPageMap[parent];
  }

  // Fallback to BA module start page
  const baNum = parseInt(parts[1], 10);
  return baStartPages[baNum] || 1;
}
